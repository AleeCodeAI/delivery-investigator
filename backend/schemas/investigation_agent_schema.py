from pydantic import BaseModel, Field 


class AgentResult(BaseModel): 
    """
    Represent the result of a delivery investigation performed by the agent.

    Attributes:
        investigation_report: Summary of the investigation findings.
        evidences: List of evidence items collected during the investigation.
        investigation_success: Whether the investigation was completed successfully.
        confidence: Confidence level of the investigation result, ranging from 0.0 to 1.0.
    """
    investigation_report: str = Field(
        description="Investigation report generated by the agent."
        )
    evidences: list[str] = Field(
        description="List of evidences collected during the investigation."
        )
    investigation_success: bool = Field(
        description="Indicates whether the investigation was successful or not."
        )
    confidence: float = Field(
        description="Confidence level of the investigation result, ranging from 0.0 to 1.0.",
        ge=0.0,
        le=1.0
        )